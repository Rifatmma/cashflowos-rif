// 👉 One engine, two homes.
//
// The brand-video renderer lives in the mw-brand-video skill
// (.claude/skills/mw-brand-video/engine/core.js), where Claude sessions
// render with it, in the mw-location-video skill (a copy), and in
// /mw/studio, where the team does. They must draw
// the same pictures, so the Studio's copy is GENERATED from the skill's:
//
//   node scripts/brandfilm-sync.mjs
//
// Edit core.js (or audit.js, engine.html, render.js, the audit scripts, the
// lessons), run this, commit all. Never edit lib/mw-brandfilm-engine.ts
// by hand — the next sync overwrites it.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const core = readFileSync(join(root, '.claude/skills/mw-brand-video/engine/core.js'), 'utf8')
const body = core.replace(/\nif \(typeof module !== 'undefined'\) module\.exports = \{ createEngine \};\s*$/, '\n')
if (body === core) throw new Error('core.js no longer ends with the module.exports line this script strips')

const out = `// @ts-nocheck
// GENERATED by scripts/brandfilm-sync.mjs from
// .claude/skills/mw-brand-video/engine/core.js — do not edit here.
//
// Untyped on purpose: it is the skill's engine verbatim, so the skill and
// this tab draw the same pictures. The typed surface is lib/mw-brandfilm.ts.

${body.replace(/^function createEngine\(/m, 'export function createEngine(')}`
if (!out.includes('export function createEngine(')) throw new Error('createEngine not found in core.js')
writeFileSync(join(root, 'lib/mw-brandfilm-engine.ts'), out)
console.log('lib/mw-brandfilm-engine.ts regenerated from core.js')

// The location-video skill (Ava for local pages) renders with the same engine.
const skills = join(root, '.claude/skills')
const brand = join(skills, 'mw-brand-video/engine'), loc = join(skills, 'mw-location-video/engine')
writeFileSync(join(loc, 'core.js'), core)
for (const f of ['VERSION', 'audit.js', 'engine.html']) writeFileSync(join(loc, f), readFileSync(join(brand, f)))
const render = readFileSync(join(brand, 'render.js'), 'utf8')
const locRender = render.replace("'.mw-brand-video')", "'.mw-location-video')")
if (locRender === render) throw new Error("render.js no longer names its home '.mw-brand-video' — update the location copy rule")
writeFileSync(join(loc, 'render.js'), locRender)
console.log('.claude/skills/mw-location-video/engine: core.js, audit.js, engine.html, render.js copied')

// The audit scripts live in the mw-video-audit skill; both video skills carry copies.
for (const f of ['audit_media.py', 'audit_voice.py'])
  for (const sk of ['mw-brand-video', 'mw-location-video'])
    writeFileSync(join(skills, sk, 'scripts', f), readFileSync(join(skills, 'mw-video-audit/scripts', f)))
console.log('audit_media.py, audit_voice.py copied from mw-video-audit to both video skills')

// What past audits taught: the skills read lessons.md; the Studio's script writer gets it here.
const lessons = readFileSync(join(skills, 'mw-video-audit/references/lessons.md'), 'utf8')
writeFileSync(join(root, 'lib/mw-video-lessons.ts'), `// GENERATED by scripts/brandfilm-sync.mjs from
// .claude/skills/mw-video-audit/references/lessons.md — do not edit here.
//
// Every mistake a video audit caught, as a rule. The Studio's script writers
// put it in their prompt so the next video does not repeat it.

export const VIDEO_LESSONS = ${JSON.stringify(lessons)}
`)
console.log('lib/mw-video-lessons.ts regenerated from lessons.md')
