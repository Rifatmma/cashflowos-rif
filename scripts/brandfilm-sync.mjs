// 👉 One engine, two homes.
//
// The brand-video renderer lives in the mw-brand-video skill
// (.claude/skills/mw-brand-video/engine/core.js), where Claude sessions
// render with it, and in /mw/studio, where the team does. They must draw
// the same pictures, so the Studio's copy is GENERATED from the skill's:
//
//   node scripts/brandfilm-sync.mjs
//
// Edit core.js, run this, commit both. Never edit lib/mw-brandfilm-engine.ts
// by hand — the next sync overwrites it.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const core = readFileSync(join(root, '.claude/skills/mw-brand-video/engine/core.js'), 'utf8')
const body = core.replace(/\nif \(typeof module !== 'undefined'\) module\.exports = \{ createEngine \};\s*$/, '\n')
if (body === core) throw new Error('core.js no longer ends with the module.exports line this script strips')

const out = `// @ts-nocheck
// GENERATED by scripts/brandfilm-sync.mjs from
// .claude/skills/mw-brand-video/engine/core.js — do not edit here.
//
// Untyped on purpose: it is the skill's engine verbatim, so the skill and
// this tab draw the same pictures. The typed surface is lib/mw-brandfilm.ts.

${body.replace(/^function createEngine\(/m, 'export function createEngine(')}`
if (!out.includes('export function createEngine(')) throw new Error('createEngine not found in core.js')
writeFileSync(join(root, 'lib/mw-brandfilm-engine.ts'), out)
console.log('lib/mw-brandfilm-engine.ts regenerated from core.js')
