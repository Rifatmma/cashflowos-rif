// ===================================================================
//  Layout audit for the brand-video engine.
//
//  auditFilm(ctx, W, H, SPEC, render) → issues[]
//
//  Draws the film at sampled moments with the canvas's fillText watched,
//  and checks every piece of text it drew against the frame: off the edge,
//  outside the platform-safe area, on top of other text, too small to read.
//  It measures what was actually drawn — not what the layout meant to do —
//  so it catches the bugs a person would see (a figure pushed out of its
//  bar and off the frame, a label running under the like/share rail).
//
//  Used by the skills (render.js … audit) and, generated by
//  scripts/brandfilm-sync.mjs, by /mw/studio before a video is sent for
//  review. Pure: it only reads what render(t) draws.
// ===================================================================
function auditFilm(ctx, W, H, SPEC, render, opts = {}) {
  const SA = render.safe || { x: 0, y: 0, w: W, h: H };
  const k = Math.min(W, H) / 1080;                 // 1 at 1080 wide
  const step = opts.step || 0.25;
  let boxes = null;
  const draw = ctx.fillText;
  ctx.fillText = function (str, x, y, maxW) {
    if (boxes && ctx.globalAlpha >= 0.5 && String(str).trim() && !/blur\((?:[2-9]|\d{2})/.test(ctx.filter || '')) {
      const m = ctx.measureText(str), tr = ctx.getTransform();
      const pts = [[x - m.actualBoundingBoxLeft, y - m.actualBoundingBoxAscent], [x + m.actualBoundingBoxRight, y + m.actualBoundingBoxDescent]]
        .map(([px, py]) => [tr.a * px + tr.c * py + tr.e, tr.b * px + tr.d * py + tr.f]);
      const size = (parseFloat((/(\d+(?:\.\d+)?)px/.exec(ctx.font) || [0, 0])[1]) || 0) * Math.hypot(tr.a, tr.b);
      boxes.push({ s: String(str), l: Math.min(pts[0][0], pts[1][0]), r: Math.max(pts[0][0], pts[1][0]), t: Math.min(pts[0][1], pts[1][1]), b: Math.max(pts[0][1], pts[1][1]), size });
    }
    return draw.call(this, str, x, y, maxW);
  };

  const issues = new Map();
  const add = (kind, scene, t, s, detail) => {
    const key = `${kind}|${scene}|${s}`;
    if (!issues.has(key)) issues.set(key, { kind, scene, t: +t.toFixed(2), text: s, detail });
  };
  try {
    SPEC.scenes.forEach((sc, si) => {
      // From the moment everything in the scene has landed to just before it
      // leaves; transitions (both scenes on screen) and blur-ins are skipped.
      for (let t = Math.min(sc.b - 0.35, sc.a + 0.6); t < sc.b - 0.3; t += step) {
        boxes = []; render(t); const bx = boxes; boxes = null;
        const label = `${si + 1} ${sc.kind}${sc.art ? ' · ' + sc.art : ''}`;
        for (const q of bx) {
          const past = Math.max(-q.l, q.r - W, -q.t, q.b - H);
          if (past > 2) add('off-frame', label, t, q.s, `${Math.round(past)}px past the ${-q.l === past ? 'left' : q.r - W === past ? 'right' : -q.t === past ? 'top' : 'bottom'} edge`);
          else if (q.size >= 16 * k) {
            const out = Math.max(SA.x - q.l, q.r - (SA.x + SA.w), SA.y - q.t, q.b - (SA.y + SA.h));
            if (out > 6 * k) add('unsafe', label, t, q.s, `${Math.round(out)}px outside the safe area${H > W * 1.5 ? ' (platform buttons / captions cover it on Reels, TikTok, Shorts)' : ''}`);
          }
          // size, like overlap, is judged once things have settled (pop-ins scale up from 0)
          if (t + step >= sc.b - 0.3 && q.size > 0 && q.size < 20 * k && q.s.length > 1) add('tiny', label, t, q.s, `${Math.round(q.size)}px text — hard to read on a phone`);
        }
        // Overlaps are judged on the settled frame only: mid-animation (a
        // number's digits rolling past each other) is motion, not layout.
        if (t + step < sc.b - 0.3) continue;
        for (let i = 0; i < bx.length; i++) for (let j = i + 1; j < bx.length; j++) {
          const p = bx[i], q = bx[j];
          if (p.s === q.s) continue;
          const w = Math.min(p.r, q.r) - Math.max(p.l, q.l), h = Math.min(p.b, q.b) - Math.max(p.t, q.t);
          if (w <= 0 || h <= 0) continue;
          const share = (w * h) / Math.min((p.r - p.l) * (p.b - p.t), (q.r - q.l) * (q.b - q.t));
          if (share > 0.12) add('overlap', label, t, `${p.s} / ${q.s}`, `${Math.round(share * 100)}% of the smaller one covered`);
        }
      }
    });
  } finally {
    ctx.fillText = draw;
    boxes = null;
  }
  return [...issues.values()];
}
if (typeof module !== 'undefined') module.exports = { auditFilm };
