// ===================================================================
//  Layout, legibility and timing audit for the brand-video engine.
//
//  auditFilm(ctx, W, H, SPEC, render, { vo }) → findings[]
//
//  Draws the film at sampled moments with the canvas's fillText watched,
//  and checks every piece of text against the frame and against Ava:
//
//    off-frame   text past the frame edge                         blocker
//    unsafe      text under platform UI (organic) → blocker;
//                only inside the stricter ad template → should fix
//    overlap     two pieces of text on top of each other          blocker
//    contrast    text vs the worst background pixel behind it,
//                WCAG 1.4.3 (4.5:1, 3:1 large; W3C F83)           should fix (blocker < 3:1)
//    tiny        x-height below ~20px at 1080 (legibility)        should fix
//    hold        on screen for less than max(1s, 0.33s/word)
//                (BBC subtitle pace 160–180 wpm)                  should fix
//    late/early  a sub-line, burst word or figure lands more than
//                0.1s after, or 0.6s before, the word Ava says
//                (headlines are exempt: they open their scene)    should fix
//
//  It measures what was actually drawn — not what the layout meant to do.
//  The pixel checks read the canvas BEFORE each text is drawn, so the
//  background behind the letters is exact. Pure apart from that.
//
//  Used by the skills (render.js … audit) and, generated by
//  scripts/brandfilm-sync.mjs, by /mw/studio.
// ===================================================================
function auditFilm(ctx, W, H, SPEC, render, opts = {}) {
  const SA = render.safe || { x: 0, y: 0, w: W, h: H };
  const FMT = render.format || '';
  const k = Math.min(W, H) / 1080;                 // 1 at 1080 wide
  const step = opts.step || 0.25;
  // the organic UI bands (account name, caption, buttons) in 9:16 — text there is unreadable on every post
  const ORG = FMT === '916' ? { x: W * .075, y: H * .13, w: W * .85, h: H * .67 } : SA;

  const colour = (() => {
    const cache = new Map();
    const c = typeof OffscreenCanvas !== 'undefined' ? new OffscreenCanvas(1, 1) : Object.assign(document.createElement('canvas'), { width: 1, height: 1 });
    const g = c.getContext('2d', { willReadFrequently: true });
    return s => { if (cache.has(s)) return cache.get(s); g.clearRect(0, 0, 1, 1); g.fillStyle = '#000'; g.fillStyle = s; g.fillRect(0, 0, 1, 1); const d = g.getImageData(0, 0, 1, 1).data; const v = [d[0], d[1], d[2], d[3] / 255]; cache.set(s, v); return v; };
  })();
  const lum = (r, g, b) => { const f = v => { v /= 255; return v <= .03928 ? v / 12.92 : Math.pow((v + .055) / 1.055, 2.4); }; return .2126 * f(r) + .7152 * f(g) + .0722 * f(b); };
  const ratio = (a, b) => { const [hi, lo] = a > b ? [a, b] : [b, a]; return (hi + .05) / (lo + .05); };

  let boxes = null, wantPixels = false;
  const draw = ctx.fillText;
  ctx.fillText = function (str, x, y, maxW) {
    if (boxes && !ctx.__clipped && ctx.globalAlpha >= 0.5 && String(str).trim() && !/blur\((?:[2-9]|\d{2})/.test(ctx.filter || '')) {
      const m = ctx.measureText(str), tr = ctx.getTransform();
      const pts = [[x - m.actualBoundingBoxLeft, y - m.actualBoundingBoxAscent], [x + m.actualBoundingBoxRight, y + m.actualBoundingBoxDescent]]
        .map(([px, py]) => [tr.a * px + tr.c * py + tr.e, tr.b * px + tr.d * py + tr.f]);
      const size = (parseFloat((/(\d+(?:\.\d+)?)px/.exec(ctx.font) || [0, 0])[1]) || 0) * Math.hypot(tr.a, tr.b);
      const q = { s: String(str), l: Math.min(pts[0][0], pts[1][0]), r: Math.max(pts[0][0], pts[1][0]), t: Math.min(pts[0][1], pts[1][1]), b: Math.max(pts[0][1], pts[1][1]), size };
      // contrast: the background is read now, before the letters cover it
      if (wantPixels && typeof ctx.fillStyle === 'string' && size >= 12 * k) {
        const x0 = Math.max(0, Math.floor(q.l)), y0 = Math.max(0, Math.floor(q.t)), x1 = Math.min(W, Math.ceil(q.r)), y1 = Math.min(H, Math.ceil(q.b));
        if (x1 - x0 > 2 && y1 - y0 > 2) {
          const img = ctx.getImageData(x0, y0, x1 - x0, y1 - y0).data, [fr, fg, fb] = colour(ctx.fillStyle), a = Math.min(1, ctx.globalAlpha * colour(ctx.fillStyle)[3]);
          const rs = [], n = (x1 - x0) * (y1 - y0), every = Math.max(1, Math.floor(n / 600));
          for (let i = 0; i < n; i += every) {
            const br = img[i * 4], bg = img[i * 4 + 1], bb = img[i * 4 + 2];
            const tl = lum(a * fr + (1 - a) * br, a * fg + (1 - a) * bg, a * fb + (1 - a) * bb), bl = lum(br, bg, bb);
            rs.push(ratio(tl, bl));
          }
          rs.sort((p, q2) => p - q2);
          q.contrast = rs[Math.floor(rs.length * .05)];          // the worst 5% of the background (F83: worst case)
        }
      }
      boxes.push(q);
    }
    return draw.call(this, str, x, y, maxW);
  };

  const found = new Map();
  const add = (sev, kind, scene, t, s, detail, rule) => {
    const key = `${kind}|${scene}|${s}`;
    if (!found.has(key)) found.set(key, { severity: sev, kind, scene, t: +t.toFixed(2), text: s, detail, rule });
  };
  const words = s => String(s).trim().split(/\s+/).filter(Boolean).length;
  const norm = w => String(w).toLowerCase().normalize('NFKD').replace(/[^\p{L}\p{N}]+/gu, '');
  // Ava's words in film time
  const said = [];
  (opts.vo || []).forEach(line => (line.words || []).forEach(([w, t]) => said.push([norm(w), line.t + t])));

  try {
    SPEC.scenes.forEach((sc, si) => {
      const label = `${si + 1} ${sc.kind}${sc.art ? ' · ' + sc.art : ''}`;
      // ---- sampled frames: from the moment things have landed to just before the cut
      for (let t = Math.min(sc.b - 0.35, sc.a + 0.6); t < sc.b - 0.3; t += step) {
        const settled = t + step >= sc.b - 0.3;
        boxes = []; wantPixels = settled; render(t); const bx = boxes; boxes = null; wantPixels = false;
        for (const q of bx) {
          const past = Math.max(-q.l, q.r - W, -q.t, q.b - H);
          if (past > 2) add('blocker', 'off-frame', label, t, q.s, `${Math.round(past)}px past the ${-q.l === past ? 'left' : q.r - W === past ? 'right' : -q.t === past ? 'top' : 'bottom'} edge`, 'Inside the frame (SMPTE ST 2046-1 graphics-safe)');
          else if (q.size >= 16 * k) {
            const out = b => Math.max(b.x - q.l, q.r - (b.x + b.w), b.y - q.t, q.b - (b.y + b.h));
            if (FMT === '916' && out(ORG) > 6 * k) add('blocker', 'unsafe', label, t, q.s, `${Math.round(out(ORG))}px under the platform buttons / caption area`, 'Platform UI safe zone (Reels / TikTok / Shorts)');
            else if (FMT !== '916' && out(SA) > 6 * k) add('should fix', 'unsafe', label, t, q.s, `${Math.round(out(SA))}px into the frame margin`, FMT === '169' ? 'SMPTE ST 2046-1 graphics-safe (90%)' : '5–10% inner margin for feed formats (inferred)');
            else if (FMT === '916' && out(SA) > 6 * k) add('should fix', 'unsafe', label, t, q.s, `${Math.round(out(SA))}px outside the ad safe zone — covered if the post is boosted`, 'Strictest ad template: x 120–888, y 288–1248 on 1080×1920');
          }
          if (!settled) continue;
          if (q.size > 0 && q.size < 20 * k && q.s.length > 1) add('should fix', 'tiny', label, t, q.s, `${Math.round(q.size)}px text — hard to read on a phone`, 'x-height ≥ ~20px at 1080 wide (Legge; inferred)');
          if (q.contrast != null) {
            const large = q.size >= 40 * k, need = large ? 3 : 4.5;
            if (q.contrast < need) add(q.contrast < 3 ? 'blocker' : 'should fix', 'contrast', label, t, q.s, `contrast ${q.contrast.toFixed(1)}:1 against the background behind it (needs ${need}:1)`, 'WCAG 2.2 SC 1.4.3, worst-case background (W3C F83)');
          }
        }
        if (!settled) continue;
        for (let i = 0; i < bx.length; i++) for (let j = i + 1; j < bx.length; j++) {
          const p = bx[i], q = bx[j];
          if (p.s === q.s) continue;
          const w = Math.min(p.r, q.r) - Math.max(p.l, q.l), h = Math.min(p.b, q.b) - Math.max(p.t, q.t);
          if (w <= 0 || h <= 0) continue;
          const share = (w * h) / Math.min((p.r - p.l) * (p.b - p.t), (q.r - q.l) * (q.b - q.t));
          if (share > 0.12) add('blocker', 'overlap', label, t, `${p.s} / ${q.s}`, `${Math.round(share * 100)}% of the smaller one covered`, 'No text on text');
        }
      }
      // ---- from the spec: how long each text is readable, and whether it lands on Ava's word
      const items = (sc.text || []).map(it => ({ ...it, end: it.out ?? sc.b }));
      if (sc.kind === 'burst') (sc.words || []).forEach((w, i, all) => items.push({ t: w.t, s: w.s, st: 'w', end: sc.variant === 'stack' ? sc.b : (all[i + 1]?.t ?? sc.b) }));
      for (const it of items) {
        const readable = it.end - (it.t + 0.3), need = it.st === 'w' ? Math.max(0.35, 0.3 * words(it.s)) : Math.max(1, 0.33 * words(it.s));
        if (it.st !== 'lab' && readable < need - 0.05) add('should fix', 'hold', label, it.t, it.s, `readable for ${readable.toFixed(1)}s, needs ${need.toFixed(1)}s (${words(it.s)} words)`, 'Reading pace 160–180 wpm (BBC subtitle guidelines); ≥1s');
        if (!said.length || it.st === 'h' || it.st === 'hx' || it.st === 'lab' || /[./@]\w/.test(it.s)) continue;   // headlines open their scene; URLs are not said
        // the first word of the item Ava actually says in this scene
        const toks = String(it.s).split(/\s+/).map(norm).filter(w => w.length > 2 || /\d/.test(w));
        // the spoken occurrence nearest to when the text appears (a word can be said twice)
        let hit = null, best = Infinity;
        for (const tok of toks) for (const s of said) {
          const [w, ts] = s;
          if (ts < sc.a - 0.5 || ts > sc.b + 0.3 || !(w === tok || (tok.length > 4 && w.startsWith(tok.slice(0, 5))))) continue;
          const dd = Math.abs((it.t + 0.1) - ts); if (dd < best) { best = dd; hit = s; }
        }
        if (!hit) continue;
        const d = (it.t + 0.1) - hit[1];          // visible ~0.1s after its cue time
        if (d > 0.25) add('should fix', 'late', label, it.t, it.s, `appears ${d.toFixed(2)}s after Ava says “${hit[0]}”`, 'Text with or just before its word (−0.2…+0.04s, from ITU-R BT.1359 sync limits; inferred)');
        else if (d < -0.6) add('should fix', 'early', label, it.t, it.s, `appears ${(-d).toFixed(2)}s before Ava says “${hit[0]}”`, 'Text with or just before its word (inferred)');
      }
    });
    // the last thing on screen must be readable before the video ends
    const end = SPEC.scenes[SPEC.scenes.length - 1];
    for (const it of end?.text || []) if (SPEC.dur - (it.t + 0.3) < 1) add('should fix', 'hold', `${SPEC.scenes.length} end`, it.t, it.s, `only ${(SPEC.dur - it.t - 0.3).toFixed(1)}s before the video ends`, '≥1s readable');
  } finally {
    ctx.fillText = draw;
    boxes = null;
  }
  const order = { blocker: 0, 'should fix': 1, 'nice to have': 2 };
  return [...found.values()].sort((a, b) => order[a.severity] - order[b.severity] || a.t - b.t);
}
if (typeof module !== 'undefined') module.exports = { auditFilm };
